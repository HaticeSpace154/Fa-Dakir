// 30 Ajzaa metadata
export const JUZ_LIST = Array.from({ length: 30 }, (_, i) => {
  const juzNum = i + 1;
  const surahsInJuz = SURAHS.filter(s => s.juz === juzNum);
  const startSurah = surahsInJuz[0] || SURAHS[0];
  return {
    id: juzNum,
    name: `الجزء ${toEasternArabic(juzNum)}`,
    startSurah: startSurah.name,
    startSurahId: startSurah.id,
    page: startSurah.page
  };
});

export function toEasternArabic(num) {
  // Keep UI counters in Western digits (0–9), including when the surrounding
  // interface is Arabic. Quran text itself is preserved as supplied.
  return String(num).replace(/[٠-٩]/g, digit => String('٠١٢٣٤٥٦٧٨٩'.indexOf(digit)));
}
